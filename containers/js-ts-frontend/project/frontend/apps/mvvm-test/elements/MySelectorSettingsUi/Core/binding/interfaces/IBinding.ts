/**
 * Определяет направление синхронизации данных между связанными объектами.
 */
export enum BindingMode {
    /**
     * Изменения передаются только от источника к цели.
     */
    OneWay = 'one-way',

    /**
     * Изменения передаются в обоих направлениях.
     */
    TwoWay = 'two-way',
}

/**
 * Базовый контракт привязки.
 *
 * Binding отвечает за установку и снятие связи между объектами.
 */
export interface IBinding {
    /**
     * Устанавливает привязку и начинает отслеживание изменений.
     */
    bind(): void;

    /**
     * Снимает привязку и прекращает отслеживание изменений.
     */
    unbind(): void;
}
